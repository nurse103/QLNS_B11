-- Bảo hiểm y tế: BHYT cá nhân (Mẫu 04b/BHYT-QĐ) và BHYT thân nhân (Mẫu 04a/BHYT-QĐ)
-- Chạy file này trong Supabase SQL Editor. Chạy lại nhiều lần cũng không sao.

-- 1. BHYT cá nhân: mỗi dòng gắn với 1 nhân viên (dsnv). Họ tên, cấp bậc, CCCD,
--    ngày sinh, giới tính, SĐT lấy từ hồ sơ nhân viên.
CREATE TABLE IF NOT EXISTS public.bhyt_ca_nhan (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    dsnv_id bigint not null references public.dsnv(id) on delete cascade,
    nam integer not null,                    -- Năm đề nghị (VD: 2027)
    loai_de_nghi text not null default 'I',  -- Mục I..VII theo mẫu
    ma_so_bhxh text,                         -- 10 số cuối thẻ BHYT
    xa_phuong text,
    tinh text,
    noi_kcb text,                            -- Nơi KCB ban đầu
    so_dien_thoai text,                      -- Để trống = lấy SĐT trong hồ sơ
    sd_tu_ngay date,                         -- Giá trị sử dụng thẻ đã cấp: từ
    sd_den_ngay date,                        --                              đến
    ghi_chu text,
    created_by uuid references public.users(id)
);
CREATE INDEX IF NOT EXISTS bhyt_cn_dsnv_id_idx ON public.bhyt_ca_nhan(dsnv_id);
CREATE INDEX IF NOT EXISTS bhyt_cn_nam_idx ON public.bhyt_ca_nhan(nam);

-- 2. BHYT thân nhân: dùng lại bảng bhyt_than_nhan đã có, thêm các cột còn thiếu.
--    Cột sẵn có: dsnv_id, moi_quan_he, ho_va_ten, ngay_sinh, gioi_tinh, ma_so_bhyt,
--    noi_cu_tru, cccd, sd_tu_ngay, sd_den_ngay, anh_bhyt, ghi_chu, created_at.
CREATE TABLE IF NOT EXISTS public.bhyt_than_nhan (
    id bigint generated by default as identity primary key,
    dsnv_id bigint references public.dsnv(id) on delete cascade,
    moi_quan_he text not null,
    ho_va_ten text not null,
    ngay_sinh date,
    gioi_tinh text,
    ma_so_bhyt text,
    noi_cu_tru text,
    cccd text,
    sd_tu_ngay date,
    sd_den_ngay date,
    anh_bhyt text,
    ghi_chu text,
    created_at timestamptz not null default timezone('utc'::text, now())
);

ALTER TABLE public.bhyt_than_nhan
    ADD COLUMN IF NOT EXISTS gia_dinh_id bigint references public.gia_dinh(id) on delete set null,
    ADD COLUMN IF NOT EXISTS nam integer,
    ADD COLUMN IF NOT EXISTS loai_de_nghi text not null default 'I',
    ADD COLUMN IF NOT EXISTS xa_phuong text,
    ADD COLUMN IF NOT EXISTS tinh text,
    ADD COLUMN IF NOT EXISTS noi_kcb text,
    ADD COLUMN IF NOT EXISTS so_dien_thoai text,
    ADD COLUMN IF NOT EXISTS created_by uuid references public.users(id);

-- Bản ghi cũ (nếu có) chưa có năm: lấy theo năm hết hạn thẻ, không có thì lấy năm sau
UPDATE public.bhyt_than_nhan
SET nam = COALESCE(EXTRACT(YEAR FROM sd_den_ngay)::int, EXTRACT(YEAR FROM now())::int + 1)
WHERE nam IS NULL;
ALTER TABLE public.bhyt_than_nhan ALTER COLUMN nam SET NOT NULL;

CREATE INDEX IF NOT EXISTS bhyt_tn_dsnv_id_idx ON public.bhyt_than_nhan(dsnv_id);
CREATE INDEX IF NOT EXISTS bhyt_tn_nam_idx ON public.bhyt_than_nhan(nam);

-- 3. RLS (cùng kiểu các bảng khác của ứng dụng: quyền được kiểm soát ở giao diện)
ALTER TABLE public.bhyt_ca_nhan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bhyt_than_nhan ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "bhyt_ca_nhan_all" ON public.bhyt_ca_nhan;
CREATE POLICY "bhyt_ca_nhan_all" ON public.bhyt_ca_nhan
    FOR ALL TO public USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "bhyt_than_nhan_all" ON public.bhyt_than_nhan;
CREATE POLICY "bhyt_than_nhan_all" ON public.bhyt_than_nhan
    FOR ALL TO public USING (true) WITH CHECK (true);

